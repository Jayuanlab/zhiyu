const baseline: SavedClaim[] = [
  { kind: "method", claim: "该方法从组得分估计基线。", quote: "The method estimates a baseline using the scores from a group of samples." },
  { kind: "experiment", claim: "实验比较了指定的基线设置。", quote: "The experiment compares the method with the specified baseline setting." },
  { kind: "limitation", claim: "作者未测量训练延迟。", quote: "The authors did not measure training latency under this experimental setting." },
];
function fixture(target: SavedClaim, extraBody = ""): GroundedResearchReportInput {
  const runId = "offline-claim-scope-unit-run";
  const sourceId = "offline-claim-scope-source";
  const eventId = "offline-source-read";
  const evidenceId = "231032c6-a1d9-4a31-97e4-2121dd749219";
  const url = "https://example.com/research-v1";
  const claims = baseline.map(item => ({ ...(item.kind === target.kind ? target : item), locator: "Observed scope", evidenceEventId: eventId }));
  const content = `# Observed scope\n\n${claims.map(item => item.quote).join("\n\n")}${extraBody}`;
  const contentHash = createHash("sha256").update(content).digest("hex");
  return { runId, report: { researchEvidence: { reportVersion: "grounded-report/v1", works: [{ sourceId, supportedClaims: claims }], gaps: [] } },
    coverage: [{ sourceId, label: "Offline lexical fixture", urls: [url], status: "complete", evidenceId, contentHash,
      totalChars: content.length, coveredChars: content.length, eventIds: [eventId] }],
    events: [{ id: eventId, runId, type: "source_checked", metadata: { receiptAuthority: "runtime", toolName: "webReadPage", ok: true,
      provider: "direct_http", method: "direct_defuddle", cleaner: "defuddle-0.19.4/zhiyu-2", url, finalUrl: url, finalUrlVerified: true,
      evidenceId, contentHash, offset: 0, contentLength: content.length, totalChars: content.length, nextOffset: null, qualityScore: 80 } }],
    snapshots: [{ sourceId, evidenceId, contentHash, url, content }] };
}
const check = (target: SavedClaim, extraBody = "") => verifyAndBuildGroundedResearchReport(fixture(target, extraBody));
const issues = (target: SavedClaim, extraBody = "") => check(target, extraBody).issues.join("\n");

describe("selected-quote metric identity and bounded local uncertainty", () => {
  it("rejects the real Math claim's Maj@K/Pass@K absent from its selected alternative, even when present in nearby context", () => {
    const text = issues(actual[2], "\nAs shown in Figure 7, RL enhances Maj@K’s performance but not Pass@K.");
    expect(text).toContain("指标 Maj@K");
    expect(text).toContain("指标 Pass@K");
  });
  it("separately detects the real Math fundamental-capabilities clause losing it seems", () => {
    expect(issues(actual[2])).toContain("it seems");
  });
  it("rejects the real R1 automated-annotation clause losing may not", () => {
    const input = fixture(actual[5]);
    const before = JSON.stringify(input.report);
    const result = verifyAndBuildGroundedResearchReport(input);
    expect(result.ok).toBe(false);
    expect(result.issues.join(" ")).toContain("may not");
    expect(result.issues.join(" ")).toContain("作者");
    expect(JSON.stringify(input.report)).toBe(before);
    expect("structured" in result).toBe(false);
  });
  it.each(actual.filter((_item, index) => index !== 2 && index !== 5))("keeps independently supported production $kind claim: $claim", item => {
    expect(check(item).ok).toBe(true);
  });
  it("accepts the same selected Math quote when its actual claim preserves the author hypothesis and adds no absent metric", () => {
    expect(check({ ...actual[2], claim: "作者推测改进似乎来自TopK正确输出提升而非基础能力增强。" }).ok).toBe(true);
  });
  it("accepts qualified automated annotation within the original long R1 quote", () => {
    expect(check({ ...actual[5], claim: "作者在本实验中指出自动化标注可能无法取得满意效果。" }).ok).toBe(true);
  });
  it("does not impose an unrelated annotation uncertainty on a claim using only the difficult-step sentence", () => {
    expect(check({ ...actual[5], claim: "作者在本实验中指出难以明确界定通用推理中的细粒度步骤。" }).ok).toBe(true);
  });
  it("does not treat manual annotation as the automated-annotation proposition", () => {
    expect(check({ ...actual[5], claim: "作者指出人工标注不利于规模化。" }).ok).toBe(true);
  });
  it("does not let a hedge in another claim clause redeem the assertive automated-annotation clause", () => {
    expect(issues({ ...actual[5], claim: "PRM可能面临步骤定义困难，自动化标注效果不佳。" })).toContain("may not");
  });
  it.each([
    ["seems that", "It seems that annotation accuracy improves with this configuration."],
    ["appears that", "It appears that annotation accuracy improves with this configuration."],
    ["might not", "Automated annotation might not produce satisfactory outcomes in this setting."],
  ])("binds the bounded %s marker to an observable corresponding action clause", (marker, quote) => {
    expect(issues({ kind: "limitation", claim: "自动化标注准确率提升。", quote })).toContain(marker);
    expect(check({ kind: "limitation", claim: "作者推测自动化标注准确率可能变化。", quote }).ok).toBe(true);
  });
  it("uses a shared scientific English anchor for an otherwise unknown technical proposition", () => {
    const quote = "It seems that SFT retains useful representations under this configuration.";
    expect(issues({ kind: "limitation", claim: "SFT保留有用表示。", quote }).toLowerCase()).toContain("it seems");
    expect(check({ kind: "limitation", claim: "作者推测SFT似乎保留有用表示。", quote }).ok).toBe(true);
  });
  it("keeps unknown unaligned paraphrases within the independently unverified semantic boundary", () => {
    const result = check({ kind: "limitation", claim: "该效果在研究之外不鲁棒。", quote: "The effect may not be robust outside the scope of this experimental study." });
    expect(result.ok).toBe(true);
    if (!result.ok) throw Error(result.issues.join(" "));
    expect(result.structured.presentation.warnings.join(" ")).toContain("独立抽查");
  });
  it("binds complete metric names and parameters while allowing cosmetic case and whitespace differences", () => {
    const quote = "The experiment measures Maj@K and Pass@1 under the same reported conditions.";
    expect(check({ kind: "experiment", claim: "实验测量maj @ k和pass @ 1。", quote }).ok).toBe(true);
    expect(issues({ kind: "experiment", claim: "实验测量Pass@K。", quote })).toContain("指标 Pass@K");
  });
  it.each([
    ["Pass@K", "The experiment measures ByPass@K under these reported evaluation conditions."],
    ["precision@10", "The experiment reports precision@1; Chapter 10 describes the evaluation setting."],
    ["Maj@N", "The experiment measures Maj@K while separately describing a variable named N."],
  ])("rejects a missing full metric identity %s despite another prefix or parameter token", (metric, quote) => {
    expect(issues({ kind: "experiment", claim: `实验使用${metric}。`, quote })).toContain(`指标 ${metric}`);
  });
  it("retains the existing numerical gate alongside the metric gate", () => {
    const text = issues({ kind: "experiment", claim: "Pass@1达到79.9%。", quote: "The experiment reports Pass@1 at 79.8% under the stated evaluation conditions." });
    expect(text).toContain("数字 79.9%");
    expect(text).not.toContain("指标 Pass@1");
  });
});
