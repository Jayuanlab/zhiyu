import { afterEach, describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { captureMemoryRevisionConfiguration, captureMemoryRevisionRuntimeOwnership, restoreMemoryRevisionConfiguration } from '../integration/brain-memory-revision-configuration.mjs';

const fixtureRoot=path.resolve(process.cwd(),'.tmp','memory-configuration-tests');
const fixtures:string[]=[];
function fixture(){
  fs.mkdirSync(fixtureRoot,{recursive:true});const directory=fs.mkdtempSync(path.join(fixtureRoot,'run-'));fixtures.push(directory);
  const files=[{file:path.join(directory,'tsconfig.json'),bytes:Buffer.from(JSON.stringify({compilerOptions:{strict:true},include:['**/*.ts']}))},{file:path.join(directory,'next-env.d.ts'),bytes:Buffer.from('import "./.tmp/next-review-12/dev/types/routes.d.ts";\n')}];
  for(const file of files)fs.writeFileSync(file.file,file.bytes);return {files,directory,records:path.join(directory,'records')};
}
afterEach(()=>{for(const directory of fixtures.splice(0)){const target=path.resolve(directory);if(!target.startsWith(fixtureRoot+path.sep))throw Error('Unexpected configuration fixture cleanup');fs.rmSync(target,{recursive:true,force:true});}});

describe('isolated Next shared configuration preservation',()=>{
  it('restores only the exact state prepared by this run and saves original bytes',()=>{
    const f=fixture();for(const file of f.files)fs.writeFileSync(file.file,'owned generated bytes');
    const prepared=captureMemoryRevisionConfiguration(f.files),result=restoreMemoryRevisionConfiguration({saved:f.files,prepared,records:f.records});
    expect(result.configurationRestored).toBe(true);expect(result.configurationConflict).toBe(false);
    for(const file of f.files){expect(fs.readFileSync(file.file)).toEqual(file.bytes);expect(fs.readFileSync(path.join(f.records,'configuration-before','build',path.basename(file.file)))).toEqual(file.bytes);}
  });
  it('preserves a concurrent external edit and backups instead of overwriting it',()=>{
    const f=fixture();for(const file of f.files)fs.writeFileSync(file.file,'owned generated bytes');
    const prepared=captureMemoryRevisionConfiguration(f.files);fs.writeFileSync(f.files[0].file,'external user edit');
    const result=restoreMemoryRevisionConfiguration({saved:f.files,prepared,records:f.records});
    expect(result.configurationConflict).toBe(true);expect(result.configurationRestored).toBe(false);
    expect(fs.readFileSync(f.files[0].file,'utf8')).toBe('external user edit');expect(fs.readFileSync(f.files[1].file)).toEqual(f.files[1].bytes);
    expect(fs.readFileSync(path.join(f.records,'configuration-conflict','build','tsconfig.json'),'utf8')).toBe('external user edit');
    expect(fs.readFileSync(path.join(f.records,'configuration-before','build','tsconfig.json'))).toEqual(f.files[0].bytes);
  });
  it('does not rewrite a file already restored and preserves unknown partial preparation',()=>{
    const f=fixture(),mtime=fs.statSync(f.files[0].file).mtimeMs;fs.writeFileSync(f.files[1].file,'unknown partial preparation');
    const result=restoreMemoryRevisionConfiguration({saved:f.files,prepared:undefined,records:f.records});
    expect(result.restorationDecisions[0].action).toBe('already_original');expect(fs.statSync(f.files[0].file).mtimeMs).toBe(mtime);
    expect(result.configurationConflict).toBe(true);expect(fs.readFileSync(f.files[1].file,'utf8')).toBe('unknown partial preparation');
  });
  it('recognizes only the selected dev stage type references and unchanged compiler options',()=>{
    const f=fixture();fs.writeFileSync(f.files[0].file,JSON.stringify({compilerOptions:{strict:true},include:['**/*.ts','.tmp/next-review-18/types/**/*.ts','.tmp/next-review-18/dev/types/**/*.ts']}));
    fs.writeFileSync(f.files[1].file,'import "./.tmp/next-review-18/dev/types/routes.d.ts";\n');
    const prepared=captureMemoryRevisionRuntimeOwnership(f.files,'18','development');expect(prepared.every((value:{ownedGeneratedState:boolean})=>value.ownedGeneratedState)).toBe(true);
    expect(restoreMemoryRevisionConfiguration({saved:f.files,prepared,records:f.records,label:'runtime'}).configurationRestored).toBe(true);
  });
  it('does not claim another stage or external compiler option changes as owned',()=>{
    const f=fixture();fs.writeFileSync(f.files[0].file,JSON.stringify({compilerOptions:{strict:false},include:['**/*.ts','.tmp/next-review-18/types/**/*.ts']}));
    fs.writeFileSync(f.files[1].file,'import "./.tmp/next-review-19/dev/types/routes.d.ts";\n');
    const prepared=captureMemoryRevisionRuntimeOwnership(f.files,'18','development');expect(prepared.every((value:{ownedGeneratedState:boolean})=>!value.ownedGeneratedState)).toBe(true);
    expect(restoreMemoryRevisionConfiguration({saved:f.files,prepared,records:f.records,label:'runtime'}).configurationConflict).toBe(true);
    expect(JSON.parse(fs.readFileSync(f.files[0].file,'utf8')).compilerOptions.strict).toBe(false);expect(fs.readFileSync(f.files[1].file,'utf8')).toContain('next-review-19');
  });
});
