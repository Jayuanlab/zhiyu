function normalizeWorkDisplayKey(value: string) {
  return value
    .replace(/^mcp__workshop-tools__/, "")
    .replace(/^mcp__[^_]+__/, "");
}

export function workDisplayLabel(value: string) {
  const normalized = normalizeWorkDisplayKey(value);
  return WORK_DISPLAY_LABELS[value] ?? WORK_DISPLAY_LABELS[normalized] ?? value;
}
